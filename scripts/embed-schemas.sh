# Turns the schemas in schema/ into a Swift source the tool carries with it.
#
# The .json files are the source of truth: they are what an outside reader consults, and
# they are what this generates from. The tool embeds them rather than reading them at run
# time because a validator that cannot find its schema would have to choose between
# refusing to write anything and writing without checking, and neither is a thing to make
# somebody's build do.
#
# `SchemaDriftTests` compares the two, so a schema edited without running this fails.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$root/Sources/SwiftMutantsSchemas/Embedded.swift"

# Written a piece at a time so that this script does not itself look to `reuse` like a
# file bearing those tags: it emits them, it is not covered by them.
copyright='FileCopyrightText'
licence='License-Identifier'

{
    printf '// SPDX-%s: 2026 swift-mutants contributors\n' "$copyright"
    printf '// SPDX-%s: MIT OR Apache-2.0\n' "$licence"
    printf '//\n'
    printf '// Generated by scripts/embed-schemas.sh from schema/. Do not edit by hand:\n'
    # shellcheck disable=SC2016  # backticks here are Swift documentation, not a command
    printf '// edit the .json and run `mise run schema-embed`. SchemaDriftTests holds the two\n'
    printf '// together, so an edit that skips the script fails rather than shipping a schema\n'
    printf '// the tool does not have.\n'
    printf '\n'
    # The documents are indented to sit inside the literal, which is not indentation
    # swift-format has any say over: changing it would change the bytes being carried.
    printf '// swift-format-ignore-file\n'
    # Inline rather than in .swiftlint.yml, because the pre-commit hook passes staged
    # files by name and swiftlint ignores `excluded` when it is given files. This file's
    # length is the length of the schemas it carries, which is not a thing to shorten.
    printf '// swiftlint:disable file_length type_body_length\n'
    printf '\n'
    printf '/// The schemas this tool ships, by the name of the document each one describes.\n'
    printf '///\n'
    printf '/// Carried in the binary rather than read from disk: a validator that could not find\n'
    printf '/// its schema would have to choose between refusing to write anything and writing\n'
    printf '/// without checking, and neither is a thing to make somebody'"'"'s build do.\n'
    printf 'public enum EmbeddedSchemas {\n'
    printf '\n'
    printf '    /// Every schema, by file name.\n'
    printf '    public static let byName: [String: String] = [\n'
    for file in "$root"/schema/*.schema.json; do
        name="$(basename "$file")"
        printf '        "%s": """\n' "$name"
        # Indent the document so the Swift literal reads as one block, and escape the
        # sequences a multiline literal would otherwise interpret.
        sed -e 's/\\/\\\\/g' -e 's/"""/\\"\\"\\"/g' -e 's/\\(/\\\\(/g' -e 's/^/            /' "$file"
        printf '            """,\n'
    done
    printf '    ]\n'
    printf '}\n'
} > "$out"

printf 'wrote %s\n' "${out#"$root"/}"
